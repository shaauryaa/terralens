"""Run TerraLens GPU jobs as private Kaggle kernels (unattended alternative to the Colab notebook).

Subcommands
    dataset   create or update the PRIVATE Kaggle dataset <user>/terralens-data with the files from
              scripts/make_data_zip.py (Source A, splits, and any training-only / challenge files)
    push      build a PRIVATE GPU kernel <user>/terralens-<name> that embeds the current src/, configs/ and
              scripts/ (no data, no .env), copies the dataset into place and runs the given commands in order
    status    print the kernel status
    fetch     download the kernel output and copy results/*.json and results/predictions/* into the repo

Credentials: KAGGLE_USERNAME and KAGGLE_API_TOKEN (or KAGGLE_KEY) from .env; never printed.

Usage:
    python scripts/kaggle_jobs.py dataset
    python scripts/kaggle_jobs.py push --name e2 --cmd "python -m terralens.models.encoder --config configs/e2_xlmr.yaml"
    python scripts/kaggle_jobs.py status --name e2
    python scripts/kaggle_jobs.py fetch --name e2
    python scripts/kaggle_jobs.py push --name e2 --cmd "..." --limit 1      # dry run: build the folder, do not push
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import os
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

BUILD = ROOT / "outputs" / "kaggle"
DATASET_SLUG = "terralens-data"
CODE_DIRS = ["src", "configs", "scripts", "annotation/prompts", "annotation/guidelines.md"]
CODE_FILES = ["pyproject.toml", "requirements.txt", "requirements-gpu.txt"]
EXCLUDE = ("__pycache__", ".pyc", "overnight_watchdog.ps1", ".ipynb_checkpoints")

KERNEL_TEMPLATE = r'''
# TerraLens Kaggle job "{name}" (generated by scripts/kaggle_jobs.py; do not edit by hand)
import base64, glob, io, os, shutil, subprocess, sys, tarfile, time
os.environ.setdefault("CUDA_VISIBLE_DEVICES", "0")
os.environ["PYTHONUNBUFFERED"] = "1"
os.environ["TOKENIZERS_PARALLELISM"] = "false"
CODE_B64 = "{code_b64}"
COMMANDS = {commands!r}
PIP = {pip!r}
OUT = "/kaggle/working"
WORK = os.path.join(OUT, "terralens")
os.makedirs(WORK, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE_B64))).extractall(WORK)
for sub in ("data/processed", "data/splits", "data/challenge", "results/predictions"):
    os.makedirs(os.path.join(WORK, sub), exist_ok=True)
found = glob.glob("/kaggle/input/**/source_a.csv", recursive=True)
assert found, "dataset with source_a.csv not attached"
src = os.path.dirname(found[0])
for f in glob.glob(os.path.join(src, "**", "*"), recursive=True):
    b = os.path.basename(f)
    if not os.path.isfile(f):
        continue
    if b.endswith("_ids.txt"):
        shutil.copy(f, os.path.join(WORK, "data/splits", b))
    elif b.startswith("challenge"):
        shutil.copy(f, os.path.join(WORK, "data/challenge", b))
    elif b.endswith(".csv") or b.endswith(".jsonl"):
        shutil.copy(f, os.path.join(WORK, "data/processed", b))
print("data:", sorted(os.listdir(os.path.join(WORK, "data/processed"))), flush=True)
subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv", shell=True)
if PIP:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *PIP])
env = dict(os.environ, PYTHONPATH=os.path.join(WORK, "src") + os.pathsep + WORK)
status = []
for cmd in COMMANDS:
    t0 = time.time()
    print("\n=== RUN:", cmd, flush=True)
    r = subprocess.run(cmd, shell=True, cwd=WORK, env=env)
    status.append((cmd, r.returncode, round((time.time() - t0) / 60, 1)))
    print(f"=== EXIT {{r.returncode}} after {{status[-1][2]}} min: {{cmd}}", flush=True)
with open(os.path.join(OUT, "job_status.tsv"), "w") as fh:
    for cmd, code, mins in status:
        fh.write(f"{{code}}\t{{mins}}\t{{cmd}}\n")
shutil.rmtree(os.path.join(WORK, "data"), ignore_errors=True)  # do not keep comment text in the output
for d in ("hf_cache",):
    shutil.rmtree(os.path.join(OUT, d), ignore_errors=True)
print("\nSTATUS", status, flush=True)
'''


def load_creds() -> dict:
    env = dict(os.environ)
    path = ROOT / ".env"
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env.setdefault(k.strip(), v.strip().strip('"').strip("'"))
    if "KAGGLE_API_TOKEN" in env:
        env.setdefault("KAGGLE_KEY", env["KAGGLE_API_TOKEN"])
    if "KAGGLE_USERNAME" not in env:
        raise SystemExit("KAGGLE_USERNAME missing from .env")
    return env


def kaggle(args: list[str], env: dict, check: bool = True) -> subprocess.CompletedProcess:
    exe = shutil.which("kaggle", path=str(Path(sys.executable).parent)) or "kaggle"
    r = subprocess.run([exe, *args], env=env, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and r.returncode != 0:
        raise SystemExit(f"kaggle {' '.join(args[:2])} failed: {r.stdout[-800:]} {r.stderr[-800:]}")
    return r


def code_tarball(include: list[str] | None = None) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in CODE_DIRS + CODE_FILES + list(include or []):
            path = ROOT / rel
            if not path.exists():
                continue
            files = [path] if path.is_file() else sorted(p for p in path.rglob("*") if p.is_file())
            for f in files:
                r = f.relative_to(ROOT).as_posix()
                if any(x in r for x in EXCLUDE) or f.name == ".env":
                    continue
                tar.add(f, arcname=r)
    return buf.getvalue()


def build_kernel(name: str, commands: list[str], user: str, pip: list[str], datasets: list[str],
                 internet: bool = True, gpu: bool = True, include: list[str] | None = None) -> Path:
    folder = BUILD / name
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    code = base64.b64encode(code_tarball(include)).decode()
    (folder / "run.py").write_text(KERNEL_TEMPLATE.format(name=name, code_b64=code, commands=commands, pip=pip),
                                   encoding="utf-8")
    meta = {"id": f"{user}/terralens-{name}", "title": f"terralens-{name}", "code_file": "run.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": gpu,
            "enable_internet": internet, "dataset_sources": [f"{user}/{d}" for d in datasets],
            "competition_sources": [], "kernel_sources": [],
            "machine_shape": "NvidiaTeslaT4" if gpu else ""}
    (folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return folder


def cmd_dataset(args, env) -> None:
    from make_data_zip import collect

    folder = BUILD / "dataset"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    for f in collect() + [ROOT / e for e in args.extra]:
        name = f.name if ("challenge" not in f.parts or f.name.startswith("challenge")) else f"challenge_{f.name}"
        shutil.copy(f, folder / name)
    meta = {"title": "terralens-data", "id": f"{env['KAGGLE_USERNAME']}/{DATASET_SLUG}",
            "licenses": [{"name": "other"}]}
    (folder / "dataset-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print("files:", sorted(p.name for p in folder.iterdir()))
    if args.limit:
        print("Dry run: not uploaded.")
        return
    exists = kaggle(["datasets", "status", meta["id"]], env, check=False)
    if exists.returncode == 0 and "ready" in exists.stdout.lower():
        r = kaggle(["datasets", "version", "-p", str(folder), "-m", args.message, "-q"], env)
    else:
        r = kaggle(["datasets", "create", "-p", str(folder), "-q"], env)  # private by default
    print(r.stdout.strip()[-400:])


def cmd_push(args, env) -> None:
    folder = build_kernel(args.name, args.cmd, env["KAGGLE_USERNAME"], args.pip, args.dataset,
                          internet=True, gpu=not args.cpu, include=args.include)
    print(f"built {folder.relative_to(ROOT)} ({(folder / 'run.py').stat().st_size / 1e3:.0f} kB)")
    if args.limit:
        print("Dry run: not pushed.")
        return
    push = ["kernels", "push", "-p", str(folder)]
    if args.timeout:
        push += ["-t", str(args.timeout)]
    r = kaggle(push, env)
    print(r.stdout.strip()[-400:])


def cmd_status(args, env) -> None:
    r = kaggle(["kernels", "status", f"{env['KAGGLE_USERNAME']}/terralens-{args.name}"], env, check=False)
    print((r.stdout + r.stderr).strip())


def cmd_fetch(args, env) -> None:
    dest = BUILD / f"{args.name}_output"
    shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True)
    r = kaggle(["kernels", "output", f"{env['KAGGLE_USERNAME']}/terralens-{args.name}", "-p", str(dest)], env,
               check=False)
    print((r.stdout + r.stderr).strip()[-600:])
    copied = 0
    for f in dest.rglob("*"):
        if not f.is_file():
            continue
        parts = f.relative_to(dest).parts
        if "results" not in parts:
            continue
        rel = Path(*parts[parts.index("results"):])
        if rel.suffix not in (".json", ".csv") or "dryrun" in f.name:
            continue
        target = ROOT / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(f, target)
        copied += 1
        print("  ->", rel.as_posix())
    print(f"copied {copied} result files")


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="sub", required=True)
    d = sub.add_parser("dataset")
    d.add_argument("--message", default="update")
    d.add_argument("--extra", nargs="*", default=[], help="more repo files to include (e.g. data/interim/x.csv)")
    d.add_argument("--limit", type=int, default=None, help="dry run: build the folder only")
    k = sub.add_parser("push")
    k.add_argument("--name", required=True)
    k.add_argument("--cmd", action="append", required=True, help="command to run (repeatable, run in order)")
    k.add_argument("--pip", nargs="*", default=["emoji", "ftfy", "regex", "pyyaml"])
    k.add_argument("--dataset", nargs="*", default=[DATASET_SLUG])
    k.add_argument("--timeout", type=int, default=None, help="kernel run-time limit in seconds")
    k.add_argument("--cpu", action="store_true")
    k.add_argument("--include", nargs="*", default=[], help="extra repo files to bundle (e.g. results/e2_mmbert.json)")
    k.add_argument("--limit", type=int, default=None, help="dry run: build the folder only")
    for name in ("status", "fetch"):
        s = sub.add_parser(name)
        s.add_argument("--name", required=True)
    args = p.parse_args(argv)
    env = load_creds()
    {"dataset": cmd_dataset, "push": cmd_push, "status": cmd_status, "fetch": cmd_fetch}[args.sub](args, env)


if __name__ == "__main__":
    main()
