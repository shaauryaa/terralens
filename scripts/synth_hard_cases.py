"""Generate hard comments with Gemini: synthetic training data (Source D) and the challenge set (T9 / T10).

Two sets, generated by separate requests and never mixed:
    synthetic   ~600 training-only comments, heavy on Against (50% Against, 25% Favour, 25% None)
    challenge   ~300 evaluation-only comments (1/3 per label), kept in data/challenge/
Phenomena: negation, sarcasm, implicit, code_mixed, romanised (+ topic_not_target for the challenge set),
in Hindi and Bengali, native script or Latin.

Labelling (``label`` subcommand): Gemini (gemini-3.5-flash-lite, the compact annotation guideline, same as the
main labelling) labels every generated comment without seeing the intended label. Claude labels the same
comments independently (``labels_claude_<set>.jsonl``, written in the Claude Code session from
``claude_todo_<set>.txt``, which shows only id and text). ``finalise`` keeps a comment only if Claude and
Gemini agree; the agreed label is used (the intended label is kept for reference).

Request budget: generation 40 comments per request; labelling 25 per request. ``--max-requests`` caps each run.

Files (data/interim/synthetic/)
    generated_<set>.jsonl        raw Gemini generations (id, text, intended_label, phenomenon, lang, script)
    labels_gemini_<set>.jsonl    Gemini labels         labels_claude_<set>.jsonl   Claude labels
    claude_todo_<set>.txt        id<TAB>text for the Claude labelling pass
Final
    data/processed/synthetic.csv           (set = synthetic; source = synthetic; training only)
    data/challenge/challenge.csv           (set = challenge; never used for training or selection)
    results/synthetic_data.json            counts, agreement, requests

Usage:
    python scripts/synth_hard_cases.py generate --set synthetic --n 600
    python scripts/synth_hard_cases.py generate --set challenge --n 300
    python scripts/synth_hard_cases.py label --set synthetic        # Gemini labels + Claude todo file
    python scripts/synth_hard_cases.py finalise
    python scripts/synth_hard_cases.py generate --set synthetic --n 40 --limit 1   # dry run: print the prompt
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import requests

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from terralens import CLAIM, LABELS  # noqa: E402
from terralens.preprocess import clean_text, tag_script  # noqa: E402

DIR = ROOT / "data" / "interim" / "synthetic"
SYN_CSV = ROOT / "data" / "processed" / "synthetic.csv"
CHALLENGE_CSV = ROOT / "data" / "challenge" / "challenge.csv"
RESULTS_JSON = ROOT / "results" / "synthetic_data.json"
# gemini-3.5-flash was tried first but returned HTTP 503 (high demand) on most requests on 2026-11-18, so
# generation uses flash-lite only.
GEN_MODELS = ["gemini-3.5-flash-lite"]
COUNTER = DIR / "gemini_requests.json"  # every Gemini call made by this script (budget < 150 overall)
PER_REQUEST = 40
SEED = 42

PHENOMENA = {
    "synthetic": ["negation", "sarcasm", "implicit", "code_mixed", "romanised"],
    "challenge": ["negation", "sarcasm", "implicit", "topic_not_target", "romanised"],
}
LABEL_MIX = {"synthetic": {"Against": 0.5, "Favour": 0.25, "None": 0.25},
             "challenge": {"Against": 1 / 3, "Favour": 1 / 3, "None": 1 / 3}}
PHENOMENON_HELP = {
    "negation": "the stance depends on a negation (e.g. 'X is not a lie', 'there is no crisis', double negation)",
    "sarcasm": "sarcasm or irony: the literal words say the opposite of what the writer means",
    "implicit": "the stance is implied, never stated with words like 'climate change is real/fake'",
    "code_mixed": "Hindi/Bengali mixed with English words and phrases inside the same sentence",
    "romanised": "Hindi/Bengali written in Latin letters (casual YouTube spelling), no native script",
    "topic_not_target": ("mentions weather, heat, floods, pollution or climate, but the writer's position on "
                         "whether climate change is a serious concern is different from what the topic suggests "
                         "(often None: talks about the topic without taking a side)"),
}
TOPICS = ["heatwaves in north India", "floods in Assam or Bangladesh", "melting Himalayan glaciers", "late or weak monsoon",
          "cyclones in the Sundarbans", "Delhi or Kolkata air pollution", "planting trees", "electric vehicles and petrol prices",
          "climate summits (COP) and rich countries", "scientists and data", "God's will / nature's cycle", "farmers and crops",
          "the YouTube video and the speaker", "sea level and coastal towns", "coal power and jobs", "plastic and rivers"]
LANG_NAME = {"hi": "Hindi", "bn": "Bengali"}


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            pass
    return out


def append_jsonl(path: Path, recs: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        for r in recs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


def plan(set_name: str, n: int) -> list[dict]:
    """One spec per request: language, script, phenomenon, label counts, topic hints (deterministic)."""
    specs, k = [], 0
    n_req = -(-n // PER_REQUEST)
    phen = PHENOMENA[set_name]
    for r in range(n_req):
        lang = ["hi", "bn"][r % 2]
        ph = phen[(r // 2) % len(phen)]
        if ph in ("romanised", "code_mixed"):
            script = "Latin letters (romanised)"
        else:
            script = "native script" if (r // 2 + r) % 2 == 0 else "Latin letters (romanised)"
        size = min(PER_REQUEST, n - r * PER_REQUEST)
        mix = LABEL_MIX[set_name]
        counts = {lab: int(round(size * f)) for lab, f in mix.items()}
        counts["None"] += size - sum(counts.values())
        topics = [TOPICS[(k + j) % len(TOPICS)] for j in range(6)]
        k += 3
        specs.append({"request": r, "lang": lang, "script": script, "phenomenon": ph, "counts": counts,
                      "topics": topics})
    return specs


def gen_prompt(spec: dict) -> str:
    counts = ", ".join(f"{v} {k}" for k, v in spec["counts"].items())
    return f"""You write realistic YouTube comments for a research dataset on stance detection.
Claim: "{CLAIM}"
Labels (the writer's stance toward the claim):
- Favour: believes climate change / global warming is real, serious or worth acting on.
- Against: denies it, calls it a hoax or exaggeration, says it is natural so not a concern, or says it does not matter.
- None: no position on the claim (off-topic, about the video, neutral facts, blame without a view, genuine questions).

Write {sum(spec['counts'].values())} different comments in {LANG_NAME[spec['lang']]}, written in {spec['script']}.
Label counts: {counts}.
Every comment must show this phenomenon: {spec['phenomenon']} = {PHENOMENON_HELP[spec['phenomenon']]}.
Topics to draw from (vary them): {', '.join(spec['topics'])}.
Make them sound like real Indian / Bangladeshi YouTube viewers: 5 to 40 words, informal, some spelling mistakes,
some emoji, varied openings. No usernames, no @mentions, no URLs, no real people's names except well-known public
figures. Do not repeat sentence templates.
Output ONLY JSON: {{"comments": [{{"text": "...", "label": "Favour|Against|None"}}, ...]}}"""


def count_request(n: int = 1) -> int:
    c = json.loads(COUNTER.read_text()) if COUNTER.exists() else {"requests": 0}
    c["requests"] += n
    COUNTER.parent.mkdir(parents=True, exist_ok=True)
    COUNTER.write_text(json.dumps(c))
    return c["requests"]


def call(model: str, key: str, prompt: str, temperature: float = 1.0) -> str:
    count_request()
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    body = {"contents": [{"role": "user", "parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": temperature, "responseMimeType": "application/json",
                                 "maxOutputTokens": 16384}}
    r = requests.post(url, headers={"x-goog-api-key": key}, json=body, timeout=300)
    if r.status_code == 429:
        raise RuntimeError("429 quota")
    if not r.ok:
        raise RuntimeError(f"HTTP {r.status_code}: {r.text[:200]}")
    cand = (r.json().get("candidates") or [{}])[0]
    return "".join(p.get("text", "") for p in cand.get("content", {}).get("parts", []))


def parse_generation(text: str, spec: dict, set_name: str, start: int) -> list[dict]:
    try:
        items = json.loads(text)["comments"]
    except (ValueError, KeyError, TypeError):
        return []
    out = []
    for i, it in enumerate(items if isinstance(items, list) else []):
        if not isinstance(it, dict) or it.get("label") not in LABELS or not str(it.get("text", "")).strip():
            continue
        t = clean_text(str(it["text"]))
        out.append({"id": f"{set_name[:3]}_{start + i:04d}", "text": t, "intended_label": it["label"],
                    "phenomenon": spec["phenomenon"], "lang": spec["lang"], "script": tag_script(t),
                    "request": spec["request"]})
    return out


def cmd_generate(args, key: str) -> None:
    out = DIR / f"generated_{args.set}.jsonl"
    have = read_jsonl(out)
    done_req = {r["request"] for r in have}
    specs = [s for s in plan(args.set, args.n) if s["request"] not in done_req]
    if args.limit:
        print(gen_prompt(specs[0]) if specs else "nothing to do")
        print(f"Dry run: {len(specs)} requests planned, none sent.")
        return
    used = 0
    next_id = max([int(r["id"].split("_")[1]) for r in have], default=-1) + 1
    for spec in specs:
        if args.max_requests is not None and used >= args.max_requests:
            print("stopped: max requests")
            break
        recs = []
        for model in GEN_MODELS:
            for attempt in range(3):
                used += 1
                try:
                    recs = parse_generation(call(model, key, gen_prompt(spec)), spec, args.set, next_id)
                except RuntimeError as err:
                    print(f"  req {spec['request']} {model}: {err}")
                    if "429" in str(err):
                        time.sleep(20)
                        break  # try the next model
                    time.sleep(5)
                    continue
                if recs:
                    break
            if recs:
                for r in recs:
                    r["model"] = model
                break
        append_jsonl(out, recs)
        next_id += len(recs) + 5
        print(f"  req {spec['request']}: {len(recs)} comments ({spec['lang']}, {spec['phenomenon']}); requests used {used}",
              flush=True)
        time.sleep(4)
    print(f"{args.set}: {len(read_jsonl(out))} generated comments in {out.relative_to(ROOT)}")


def cmd_label(args, key: str) -> None:
    from label_llm import ANNOTATORS, label_items

    gen = pd.DataFrame(read_jsonl(DIR / f"generated_{args.set}.jsonl")).drop_duplicates("id")
    gen = gen.drop_duplicates("text")
    items = gen[["id", "text"]].assign(lang_check=False)
    # Claude todo file: id and text only (no intended label, no Gemini label).
    todo = DIR / f"claude_todo_{args.set}.txt"
    todo.write_text("\n".join(f"{r.id}\t{r.text}" for r in items.itertuples()) + "\n", encoding="utf-8")
    print(f"wrote {todo.relative_to(ROOT)} ({len(items)} items) for the Claude pass")
    if args.limit:
        print("Dry run: no Gemini requests.")
        return
    stats = label_items(items, ANNOTATORS["gemini"], DIR / f"labels_gemini_{args.set}.jsonl", args.set,
                        args.max_requests, key)
    total = count_request(stats["requests"])
    print(stats, f"total Gemini requests so far: {total}")


def labels(path: Path) -> pd.Series:
    recs = [r for r in read_jsonl(path) if r.get("label") in LABELS]
    return pd.DataFrame(recs, columns=["id", "label"]).drop_duplicates("id", keep="last").set_index("id")["label"]


def finalise_set(set_name: str) -> tuple[pd.DataFrame, dict]:
    gen = pd.DataFrame(read_jsonl(DIR / f"generated_{set_name}.jsonl")).drop_duplicates("id").drop_duplicates("text")
    gem, cla = labels(DIR / f"labels_gemini_{set_name}.jsonl"), labels(DIR / f"labels_claude_{set_name}.jsonl")
    gen["label_gemini"], gen["label_claude"] = gen["id"].map(gem), gen["id"].map(cla)
    both = gen.dropna(subset=["label_gemini", "label_claude"])
    agree = both[both["label_gemini"] == both["label_claude"]].copy()
    agree["label"] = agree["label_claude"]
    stats = {"generated": len(gen), "labelled_by_both": len(both), "agree": len(agree),
             "agreement_pct": round(100 * len(agree) / max(1, len(both)), 1),
             "agree_with_intended": int((agree["label"] == agree["intended_label"]).sum()),
             "label": {lab: int((agree["label"] == lab).sum()) for lab in LABELS},
             "by_phenomenon": {str(k): int(v) for k, v in agree["phenomenon"].value_counts().items()},
             "by_lang": {str(k): int(v) for k, v in agree["lang"].value_counts().items()}}
    try:
        from sklearn.metrics import cohen_kappa_score

        stats["cohen_kappa_claude_gemini"] = round(float(cohen_kappa_score(both["label_claude"], both["label_gemini"])), 4)
    except ValueError:
        pass
    agree["tags"] = agree["phenomenon"].map(lambda p: json.dumps([p] if p in PHENOMENON_HELP else []))
    return agree, stats


def cmd_finalise(args) -> None:
    from terralens.splits import load_splits

    out = {"experiment_id": "synthetic_data", "script": "scripts/synth_hard_cases.py", "seed": SEED, "timestamp": now(),
           "config": {"generator": GEN_MODELS, "labellers": ["Claude (Claude Code session)", "gemini-3.5-flash-lite"],
                      "rule": "keep only if Claude and Gemini agree; agreed label used"}}
    sets = {}
    for set_name in ("synthetic", "challenge"):
        if not (DIR / f"generated_{set_name}.jsonl").exists():
            continue
        df, stats = finalise_set(set_name)
        sets[set_name] = df
        out[set_name] = stats
    # Synthetic training data must not overlap val / test / challenge (exact cleaned text and near duplicates
    # are checked again by scripts/near_dup_check.py).
    if "synthetic" in sets and "challenge" in sets:
        before = len(sets["synthetic"])
        sets["synthetic"] = sets["synthetic"][~sets["synthetic"]["text"].isin(set(sets["challenge"]["text"]))]
        out["synthetic"]["dropped_same_text_as_challenge"] = before - len(sets["synthetic"])
    cols = ["id", "text", "label", "lang", "script", "source", "video_id", "tags", "intended_label", "phenomenon"]
    if "synthetic" in sets:
        s = sets["synthetic"].assign(source="synthetic", video_id="")[cols]
        SYN_CSV.parent.mkdir(parents=True, exist_ok=True)
        s.to_csv(SYN_CSV, index=False, encoding="utf-8")
        print(f"wrote {SYN_CSV.relative_to(ROOT)} ({len(s)})")
    if "challenge" in sets:
        c = sets["challenge"].assign(source="challenge", video_id="")[cols]
        CHALLENGE_CSV.parent.mkdir(parents=True, exist_ok=True)
        c.to_csv(CHALLENGE_CSV, index=False, encoding="utf-8")
        print(f"wrote {CHALLENGE_CSV.relative_to(ROOT)} ({len(c)})")
    _ = load_splits  # val/test overlap is handled by near_dup_check.py
    RESULTS_JSON.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in out.items() if k in ("synthetic", "challenge")}, indent=1))


def main(argv=None) -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--set", choices=["synthetic", "challenge"], required=True)
    g.add_argument("--n", type=int, required=True)
    g.add_argument("--max-requests", type=int, default=None)
    g.add_argument("--limit", type=int, default=None, help="dry run: print the first prompt, send nothing")
    lab = sub.add_parser("label")
    lab.add_argument("--set", choices=["synthetic", "challenge"], required=True)
    lab.add_argument("--max-requests", type=int, default=None)
    lab.add_argument("--limit", type=int, default=None, help="dry run: write the Claude todo file only")
    sub.add_parser("finalise")
    args = p.parse_args(argv)
    if args.cmd == "finalise":
        cmd_finalise(args)
        return
    from label_llm import load_env

    key = load_env()["GEMINI_API_KEY"]
    {"generate": cmd_generate, "label": cmd_label}[args.cmd](args, key)


if __name__ == "__main__":
    main()
